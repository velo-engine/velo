fn test_decode_matches_libwebp() {
	g := webp.decode(gradient_webp)!
	assert g.width == 37 && g.height == 11
	assert crc32.sum(g.rgba) == 0x731975bb
	p := webp.decode(palette_webp)!
	assert p.width == 29 && p.height == 7
	assert crc32.sum(p.rgba) == 0x30d5efa1
	w, h := webp.info(palette_webp)!
	assert w == 29 && h == 7
}

fn test_rejects_non_webp_and_lossy() {
	assert !webp.is_webp([u8(0x89), `P`, `N`, `G`])
	if _ := webp.decode([u8(1), 2, 3]) {
		assert false
	}
	mut lossy := gradient_webp.clone()
	lossy[15] = ` ` // 'VP8L' -> 'VP8 '
	webp.decode(lossy) or {
		assert err.msg().contains('lossy')
		return
	}
	assert false
}

fn test_asset_kind_and_header_size() {
	assert assets.kind_from_ext('page.webp') == .texture
	assert assets.kind_from_ext('hero.atlas') == .text
	path := os.join_path(os.temp_dir(), 'velo_webp_test.webp')
	os.write_file_array(path, gradient_webp)!
	defer {
		os.rm(path) or {}
	}
	w, h := assets.image_size(path)!
	assert w == 37 && h == 11
}

// Real lossless WebP pages: every .webp under SPINE42_REFS decodes to a sane RGBA image (skipped when unset).
fn test_real_pages_decode() {
	refs := os.getenv('SPINE42_REFS')
	if refs == '' || !os.is_dir(refs) {
		println('skipped: set SPINE42_REFS to a folder containing lossless .webp pages')
		return
	}
	for path in os.walk_ext(refs, '.webp') {
		img := webp.decode(os.read_bytes(path)!) or { continue } // lossy pages are rejected by design
		assert img.width > 0 && img.height > 0, path
		assert img.rgba.len == img.width * img.height * 4, path
	}
}
